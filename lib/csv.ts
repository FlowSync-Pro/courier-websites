import { categoryLabel, serviceName, vehicleName } from "@/lib/catalog";
import type { ClientRow, ExpenseRow, JobRow } from "@/lib/db";
import { csvCell, formatMoney } from "@/lib/utils";

const HEADERS = [
  "section",
  "id",
  "date",
  "name",
  "business_name",
  "phone",
  "email",
  "status",
  "source",
  "recurring",
  "schedule",
  "client",
  "service",
  "vehicle",
  "driver",
  "pickup",
  "dropoff",
  "amount",
  "miles",
  "paid",
  "pallets",
  "pieces",
  "weight",
  "liftgate",
  "waiting_minutes",
  "driver_pay",
  "category",
  "notes",
  "receipt",
  "delivery_photo",
];

function line(values: Array<string | number | null | undefined>) {
  return values.map((value) => csvCell(value)).join(",");
}

export function buildBooksCsv(clients: ClientRow[], jobs: JobRow[], expenses: ExpenseRow[]) {
  const body = [
    line(HEADERS),
    ...clients.map((item) =>
      line([
        "client",
        item.id,
        item.created_at.slice(0, 10),
        item.name,
        item.business_name,
        item.phone,
        item.email,
        "",
        item.source,
        item.recurring ? "yes" : "no",
        item.schedule,
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        item.notes,
        "",
        "",
      ]),
    ),
    ...jobs.map((item) =>
      line([
        "job",
        item.id,
        item.job_date,
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        item.client_name ?? "",
        serviceName(item.service_id),
        item.vehicle_id ? vehicleName(item.vehicle_id) : "",
        item.driver_name,
        item.pickup,
        item.dropoff,
        formatMoney(item.amount_cents),
        item.miles ?? "",
        item.paid ? "yes" : "no",
        item.pallets,
        item.pieces,
        item.weight,
        item.liftgate ? "yes" : "no",
        item.waiting_minutes ?? "",
        item.driver_pay_cents == null ? "" : formatMoney(item.driver_pay_cents),
        "",
        item.notes,
        "",
        item.pod_photo_path,
      ]),
    ),
    ...expenses.map((item) =>
      line([
        "expense",
        item.id,
        item.expense_date,
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        item.vehicle_id ? vehicleName(item.vehicle_id) : "",
        "",
        "",
        "",
        formatMoney(item.amount_cents),
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        "",
        categoryLabel(item.category),
        item.notes,
        item.receipt_path,
        "",
      ]),
    ),
  ];
  return `\uFEFF${body.join("\n")}\n`;
}
